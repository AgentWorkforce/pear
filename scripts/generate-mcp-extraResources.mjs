#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { mcpExtraResourceFilters } from './lib/dependency-closure.mjs'

const rootDir = resolve(fileURLToPath(new URL('..', import.meta.url)))
const outputPath = resolve(rootDir, 'electron-builder.mcp-resources.yml')
const check = process.argv.includes('--check')

function generatedConfig() {
  const filters = mcpExtraResourceFilters(rootDir)
    .map((filter) => `      - ${quoteYaml(filter)}`)
    .join('\n')

  return `# Generated by scripts/generate-mcp-extraResources.mjs. Do not edit by hand.\nextraResources:\n  - from: resources/app-icon.png\n    to: app-icon.png\n  - from: bin/relayfile-mount\n    to: bin/relayfile-mount\n  - from: resources/agent-relay-mcp/launch.sh\n    to: agent-relay-mcp/launch.sh\n  - from: resources/agent-relay-mcp/launch.cmd\n    to: agent-relay-mcp/launch.cmd\n  # External MCP clients are normal processes and cannot traverse app.asar.\n  # Ship the agent-relay MCP entrypoint and its runtime dependency closure as\n  # regular files under Resources/agent-relay-mcp/node_modules.\n  - from: node_modules\n    to: agent-relay-mcp/node_modules\n    filter:\n${filters}\n`
}

function quoteYaml(value) {
  return `'${value.replace(/'/g, "''")}'`
}

const expected = generatedConfig()

if (check) {
  const actual = readFileSync(outputPath, 'utf8')
  if (actual !== expected) {
    console.error(`${outputPath} is stale. Run npm run generate:mcp-resources and commit the result.`)
    process.exit(1)
  }
  console.log('MCP extraResources config is in sync.')
} else {
  writeFileSync(outputPath, expected)
  console.log(`Wrote ${outputPath}`)
}
